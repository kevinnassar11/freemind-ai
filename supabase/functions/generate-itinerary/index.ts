// FreeMind AI - generate-itinerary Edge Function
//
// DEPLOYED, but inert until ANTHROPIC_API_KEY is set - it checks for the key
// itself (see `if (!ANTHROPIC_API_KEY)` below) and returns 503 without one,
// which is exactly the failure PlacesRepositoryImpl already treats as "fall
// back to the on-device ItineraryComposer". So right now this function is
// live but never reached in practice: every call 503s and the app silently
// uses the template-based composer instead, same as before deployment.
//
// Turns a free-form trip-planning prompt typed into the Places tab's Prompt
// mode (e.g. "I'm travelling for 10 days to Turkey, staying in Istanbul, and
// I love swimming, eating, and sights") into a single paragraph day-by-day
// itinerary, generated by the Claude API. To make it actually generate real
// text, set the key yourself (this is a secret - only you should ever type
// it, never paste it to an assistant or a chat) and redeploy:
//
//   supabase secrets set ANTHROPIC_API_KEY="sk-ant-..."
//   supabase functions deploy generate-itinerary
//
// Auth: unlike stamp-role and notify-favorites, this function needs no
// special-cased auth model - it's only ever called by an already-signed-in
// user (stamp-role has already run by the time the Places tab is usable), so
// the project's normal Firebase third-party auth integration checks the
// caller's JWT at the gateway before this code ever runs. That's why there's
// no [functions.generate-itinerary] override in config.toml - it uses the
// default verify_jwt = true.

const ANTHROPIC_API_KEY = Deno.env.get("ANTHROPIC_API_KEY") ?? "";
const MODEL = "claude-sonnet-5";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, apikey, content-type",
};

function jsonResponse(body: unknown, status: number): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...corsHeaders, "Content-Type": "application/json" },
  });
}

const SYSTEM_PROMPT = `You are a travel planner inside a maps app. The user
will describe a trip in their own words - destination, length of stay, and
what they enjoy. Reply with ONE cohesive paragraph (no headers, no bullet
points, no markdown) that plans it day by day: for each day, name where to
eat, where to swim (only if the trip supports it), and what sights to see,
using real, specific, plausible suggestions for the destination. Keep it
tight enough to read in under a minute. If the message doesn't actually
describe a trip, say so in one sentence instead of inventing one.`;

interface RequestBody {
  prompt?: string;
}

interface AnthropicResponse {
  content: { type: string; text?: string }[];
}

async function handle(req: Request): Promise<Response> {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  if (!ANTHROPIC_API_KEY) {
    console.error("[generate-itinerary] ANTHROPIC_API_KEY is unset");
    return jsonResponse({ error: "not_configured" }, 503);
  }

  let prompt: string;
  try {
    const body = (await req.json()) as RequestBody;
    prompt = (body.prompt ?? "").trim();
  } catch {
    return jsonResponse({ error: "invalid_body" }, 400);
  }
  if (!prompt) return jsonResponse({ error: "empty_prompt" }, 400);

  const res = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: {
      "x-api-key": ANTHROPIC_API_KEY,
      "anthropic-version": "2023-06-01",
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      model: MODEL,
      max_tokens: 700,
      system: SYSTEM_PROMPT,
      messages: [{ role: "user", content: prompt }],
    }),
  });

  if (!res.ok) {
    console.error("[generate-itinerary] Anthropic call failed", res.status, await res.text());
    return jsonResponse({ error: "upstream_failed" }, 502);
  }

  const data = (await res.json()) as AnthropicResponse;
  const itinerary = data.content.find((block) => block.type === "text")?.text?.trim();
  if (!itinerary) return jsonResponse({ error: "empty_response" }, 502);

  return jsonResponse({ itinerary }, 200);
}

Deno.serve(async (req) => {
  try {
    return await handle(req);
  } catch (error) {
    console.error("[generate-itinerary] UNHANDLED", error);
    return jsonResponse({ error: "unexpected_error", detail: String(error).slice(0, 500) }, 500);
  }
});
